package jsonfile

import (
	"encoding/json"
	"os"
	"path/filepath"
)

// Read loads a JSON file into target without interpreting missing/corrupt errors.
func Read(path string, target any) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	return json.Unmarshal(data, target)
}

// Write0600 writes indented JSON with owner-only file permissions.
func Write0600(path string, value any) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return err
	}
	data, err := json.MarshalIndent(value, "", "  ")
	if err != nil {
		return err
	}
	data = append(data, '\n')
	return os.WriteFile(path, data, 0o600)
}
